"""Prowler one-shot samples for CAR fire_sound_2. Run with Blender's Python.

The weapon patch disables looping_sounds and retains the original CAR event
names. Output is 48 kHz stereo PCM16 with only RIFF/fmt/data chunks.
"""
import json
import sys
import wave
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audio_tools import load, SR

ROOT = Path(__file__).resolve().parents[1]
APEX = ROOT / "audio_raw/apex/audio"
OUT = ROOT / "mod_src/audio"
CAR_RPS = 14.1
REPORT = {"mode": "per-shot", "rps": CAR_RPS, "events": {}}


def src(name):
    return load(str(APEX / (name + ".wav")))


def envelope(a):
    width = int(SR * 0.002)
    return np.convolve(np.abs(a).mean(axis=1), np.ones(width) / width, mode="same")


def period(a):
    env = envelope(a[:SR * 2])[::48]  # 1 kHz envelope; avoid quadratic work at 48 kHz
    env -= env.mean()
    corr = np.correlate(env, env, mode="full")[len(env) - 1:]
    return (60 + int(np.argmax(corr[60:110]))) / 1000


def fade(a, seconds, tail=0.05):
    a = a[:round(seconds * SR)].copy()
    attack, end = min(len(a), round(0.0005 * SR)), min(len(a), round(tail * SR))
    a[:attack] *= np.linspace(0, 1, attack)[:, None]
    a[-end:] *= np.linspace(1, 0, end)[:, None]
    return a


def mix(*layers):
    result = np.zeros((max(len(a) for a, gain in layers), 2), np.float32)
    for a, gain in layers:
        result[:len(a)] += a * gain
    return result


def cycle(a):
    duration = period(a)
    width = round(duration * SR)
    phase = max(0, int(np.argmax(np.diff(envelope(a[:width + 1])))) - round(0.003 * SR))
    start = phase + width
    return fade(a[start:start + width], duration, 0.012), duration


def shot_from_loop(loop, tail):
    body, duration = cycle(loop)
    # Append an actual decay instead of the next attacks from a continuous loop.
    decay = fade(tail, 0.15, 0.09)
    body_rms = float(np.sqrt(np.mean(body ** 2)))
    tail_rms = max(float(np.sqrt(np.mean(decay ** 2))), 1e-9)
    decay *= min(1.0, 0.25 * body_rms / tail_rms)
    offset = len(body) - round(0.012 * SR)
    result = np.zeros((offset + len(decay), 2), np.float32)
    result[:len(body)] += body
    result[offset:] += decay
    return result, duration


def overlap_peak(a):
    stream = np.zeros((round(18 * SR / CAR_RPS) + len(a), 2), np.float32)
    for k in range(18):
        start = round(k * SR / CAR_RPS)
        stream[start:start + len(a)] += a
    return float(np.max(np.abs(stream)))


def write(event, a, per_shot=True):
    peak = float(np.max(np.abs(a)))
    overlap = overlap_peak(a) if per_shot else peak
    gain = min(1.0, 0.98 / max(peak, 1e-9), 0.92 / max(overlap, 1e-9))
    a = a * gain
    directory = OUT / event
    directory.mkdir(parents=True, exist_ok=True)
    with wave.open(str(directory / "1.wav"), "wb") as wav:
        wav.setnchannels(2)
        wav.setsampwidth(2)
        wav.setframerate(SR)
        wav.writeframes((np.clip(a, -1, 1) * 32767).astype("<i2").tobytes())
    (OUT / (event + ".json")).write_text(json.dumps({"EventId": [event], "AudioSelectionStrategy": "sequential"}, indent=1), encoding="utf-8")
    REPORT["events"][event] = {
        "seconds": round(len(a) / SR, 4), "peak": round(peak * gain, 5),
        "rms": round(float(np.sqrt(np.mean(a ** 2))), 5),
        "overlap_peak_14_1rps": round(overlap * gain, 5), "gain": round(gain, 5),
    }


def main():
    close = src("Wpn_ProwlerPDW_3p_WpnFire_Loop_Close_2ch_v1_01")
    mid = src("Wpn_ProwlerPDW_3p_WpnFire_Loop_Mid_2ch_v1_01")
    mech, mech_period = cycle(src("Wpn_ProwlerPDW_1p_WpnFire_Loop_Mech_2ch_v1_01"))
    first = fade(src("Wpn_ProwlerPDW_1p_WpnFire_FirstShot_Close_2ch_v1_01"), 0.25, 0.065)
    third, close_period = shot_from_loop(close, src("Wpn_ProwlerPDW_3p_WpnFire_Tail_Mid_2ch_v1_01"))
    npc, mid_period = shot_from_loop(mid, src("Wpn_ProwlerPDW_3p_WpnFire_Tail_Mid_2ch_v1_02"))
    write("Weapon_Car_SecondShot_1P", mix((first, 1.0), (mech, 0.2)))
    write("Weapon_Car_SecondShot_3P", third)
    write("Weapon_Car_SecondShot_NPC", npc)
    write("car_LowAmmo_Shot1", mix(
        (src("Wpn_ProwlerPDW_3p_WpnFire_LowAmmo_Pop_2ch_v1_01"), 0.8),
        (src("Wpn_ProwlerPDW_3p_WpnFire_LowAmmo_Mech_2ch_v1_01"), 0.6)), per_shot=False)
    REPORT["source_periods_ms"] = {"close": close_period * 1000, "mid": mid_period * 1000, "mech": mech_period * 1000}
    # Only remove files previously generated by this builder; never installed mods.
    obsolete = ("Weapon_Car_FirstShot_1P", "Weapon_Car_Loop_1P", "Weapon_Car_Loop_3P", "Weapon_Car_Loop_3P_NPC_A",
                "Weapon_Car_LoopEnd_1P", "Weapon_Car_LoopEnd_3P", "Weapon_Car_LoopEnd_NPC")
    for event in obsolete:
        definition, directory = OUT / (event + ".json"), OUT / event
        if definition.exists():
            definition.unlink()
        if directory.is_dir():
            for wav in directory.glob("*.wav"):
                wav.unlink()
            if not any(directory.iterdir()):
                directory.rmdir()
    (ROOT / "build/audio_report.json").write_text(json.dumps(REPORT, indent=1), encoding="utf-8")
    print("AUDIO_OK", json.dumps(REPORT))


if __name__ == "__main__":
    main()
